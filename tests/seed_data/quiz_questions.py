def _a(correct_uz, correct_ru, wrong_uz_ru_pairs):
    opts = [(True, {"uz": correct_uz, "ru": correct_ru})]
    for uz, ru in wrong_uz_ru_pairs:
        opts.append((False, {"uz": uz, "ru": ru}))
    return opts


